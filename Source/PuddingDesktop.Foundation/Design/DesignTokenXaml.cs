using System.Globalization;
using System.Text;

namespace PuddingDesktop.Foundation.Design;

/// <summary>
/// 把 <see cref="DesignTokens"/> 渲染成 WinUI 资源字典片段。
///
/// 为什么不直接手写 Tokens.xaml：两份真源一定会漂移。这里让代码是唯一真源，
/// XAML 是生成物，再由测试断言"磁盘上的 Tokens.xaml 与生成结果逐字相同"。
/// </summary>
public static class DesignTokenXaml
{
    /// <summary>生成物相对仓库根目录的路径约定。</summary>
    public const string RelativePath = "Source/PuddingDesktop/Themes/DesignTokens.xaml";

    /// <summary>渲染完整的 <c>ResourceDictionary</c> 文档。</summary>
    public static string Write()
    {
        var builder = new StringBuilder();
        builder.AppendLine("""
            <!--
              generated by PuddingDesktop.Foundation.Design.DesignTokenXaml.Write()
              do not edit by hand: edit DesignTokens.cs and regenerate,
              DesktopXamlTokenAdoptionTests fails when this file drifts.
            -->
            <ResourceDictionary
                xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"
                xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
            """);

        foreach (var token in DesignTokens.FontSizes)
        {
            builder.AppendLine(Invariant($"  <!-- {token.Usage} -->"));
            builder.AppendLine(Invariant($"  <x:Double x:Key=\"{token.Name}\">{token.Size}</x:Double>"));
        }

        builder.AppendLine();
        foreach (var token in DesignTokens.CornerRadii)
        {
            builder.AppendLine(Invariant($"  <!-- {token.Usage} -->"));
            builder.AppendLine(Invariant($"  <CornerRadius x:Key=\"{token.Name}\">{token.Radius}</CornerRadius>"));
        }

        builder.AppendLine("</ResourceDictionary>");
        return builder.ToString();
    }

    private static string Invariant(FormattableString value) =>
        value.ToString(CultureInfo.InvariantCulture);
}
